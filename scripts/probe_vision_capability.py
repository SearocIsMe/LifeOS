"""probe_vision_capability.py -- strictly verify whether a model actually reads images.

Design (why this is a real test, not a guess):
  * The image carries UNIQUE, non-guessable information:
      - two large digits "47" drawn as a black/white grid
      - left half filled RED, right half filled BLUE (vertical split)
  * We ask the model to report digits AND colors.
  * A text-only model cannot know these -> it will hallucinate or refuse.
  * CONTROL run: same prompt, NO image. If the answer is the same as the image
    run, the model clearly is not using the image.

Pure stdlib (no PIL needed): the PNG is generated by hand with zlib + struct.

Env:
    LLM_API_KEY  (required)
    LLM_BASE_URL (default https://open.bigmodel.cn/api/paas/v4/)
    VLLM_MODEL   (default GLM-4.6V)

Usage:
    docker cp scripts/probe_vision_capability.py xiaozhi-esp32-server:/tmp/
    docker exec -e LLM_API_KEY=<key> -e VLLM_MODEL=GLM-4.6V \
        xiaozhi-esp32-server python /tmp/probe_vision_capability.py
"""

import base64
import json
import os
import struct
import sys
import urllib.error
import urllib.request
import zlib

# --------------------------------------------------------------------------- #
# Minimal PNG writer (RGB, 8-bit)
# --------------------------------------------------------------------------- #

W, H = 96, 48

# 5x7 bitmap font for digits we need
GLYPH = {
    "4": [
        "10001",
        "10001",
        "10001",
        "11111",
        "00001",
        "00001",
        "00001",
    ],
    "7": [
        "11111",
        "00001",
        "00010",
        "00100",
        "01000",
        "01000",
        "01000",
    ],
}

RED = (220, 40, 40)
BLUE = (40, 60, 220)
WHITE = (255, 255, 255)
BLACK = (0, 0, 0)


def _build_pixels() -> list[list[tuple[int, int, int]]]:
    """Left half red, right half blue; digits '47' drawn in black on a white band."""
    rows: list[list[tuple[int, int, int]]] = []
    for y in range(H):
        row: list[tuple[int, int, int]] = []
        for x in range(W):
            row.append(RED if x < W // 2 else BLUE)
        rows.append(row)

    # white band in the middle for legibility
    band_top, band_bottom = 12, 36
    for y in range(band_top, band_bottom):
        for x in range(W // 2 - 28, W // 2 + 28):
            rows[y][x] = WHITE

    # draw "4" then "7" inside the band (scale 2x)
    scale = 2
    origin_x = W // 2 - 24
    origin_y = band_top + 2
    for idx, ch in enumerate("47"):
        glyph = GLYPH[ch]
        gx = origin_x + idx * (5 * scale + 8)
        for gy, line in enumerate(glyph):
            for cx, bit in enumerate(line):
                if bit != "1":
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        px, py = gx + cx * scale + dx, origin_y + gy * scale + dy
                        if 0 <= px < W and 0 <= py < H:
                            rows[py][px] = BLACK
    return rows


def _png_bytes() -> bytes:
    rows = _build_pixels()
    raw = bytearray()
    for row in rows:
        raw.append(0)  # filter type 0
        for r, g, b in row:
            raw += bytes((r, g, b))
    compressed = zlib.compress(bytes(raw), 9)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)  # 8-bit, truecolor
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", compressed)
        + chunk(b"IEND", b"")
    )


# --------------------------------------------------------------------------- #
# API call
# --------------------------------------------------------------------------- #

PROMPT = (
    "请只根据图片回答两点，不要猜测：\n"
    "1) 图中画的是哪两个阿拉伯数字？（按从左到右的顺序）\n"
    "2) 图片左半边和右半边分别是什么颜色？\n"
    "若你无法看到图片，请直接回答「无法读取图片」。"
)


def call(key: str, base: str, model: str, with_image: bool) -> tuple[bool, str]:
    content: list[dict] = [{"type": "text", "text": PROMPT}]
    if with_image:
        uri = "data:image/png;base64," + base64.b64encode(_png_bytes()).decode()
        content.append({"type": "image_url", "image_url": {"url": uri}})

    body = json.dumps(
        {
            "model": model,
            "messages": [{"role": "user", "content": content}],
            "max_tokens": 200,
        },
        ensure_ascii=False,
    ).encode("utf-8")

    req = urllib.request.Request(
        base.rstrip("/") + "/chat/completions",
        data=body,
        headers={"Content-Type": "application/json", "Authorization": "Bearer " + key},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            data = json.loads(r.read().decode("utf-8"))
        return True, data["choices"][0]["message"]["content"]
    except urllib.error.HTTPError as exc:
        return False, f"HTTP {exc.code}: " + exc.read().decode("utf-8", "replace")[:300]
    except Exception as exc:  # noqa: BLE001
        return False, f"{type(exc).__name__}: {exc}"


def main() -> int:
    key = os.environ.get("LLM_API_KEY", "")
    base = os.environ.get("LLM_BASE_URL", "https://open.bigmodel.cn/api/paas/v4/")
    model = os.environ.get("VLLM_MODEL", "GLM-4.6V")
    if not key:
        print("FAIL: LLM_API_KEY empty")
        return 1

    print(f"model = {model}")
    print(f"base  = {base}")
    print(f"image = {W}x{H} PNG, digits '47', left RED / right BLUE\n")

    ok_i, ans_i = call(key, base, model, with_image=True)
    print("=== WITH IMAGE ===")
    print(ans_i if ok_i else "ERROR: " + ans_i)

    ok_c, ans_c = call(key, base, model, with_image=False)
    print("\n=== CONTROL (no image) ===")
    print(ans_c if ok_c else "ERROR: " + ans_c)

    print("\n=== VERDICT ===")
    if not ok_i:
        print("FAIL: image request itself errored -> model/endpoint unusable for vision")
        return 2

    has_digits = ("47" in ans_i) or ("4" in ans_i and "7" in ans_i)
    has_colors = ("红" in ans_i and "蓝" in ans_i)
    says_blind = "无法读取图片" in ans_i

    print(f"  mentions digits 4&7 : {has_digits}")
    print(f"  mentions red & blue  : {has_colors}")
    print(f"  admits cannot see    : {says_blind}")

    if says_blind:
        print("  -> TEXT-ONLY behaviour: model reports it cannot see the image")
        return 3
    if has_digits and has_colors:
        print("  -> PASS: model really read the image (digits + colors correct)")
        return 0
    print("  -> INCONCLUSIVE: answer did not match the image content")
    print("     (compare with CONTROL: if identical, model ignored the image)")
    return 4


if __name__ == "__main__":
    sys.exit(main())
